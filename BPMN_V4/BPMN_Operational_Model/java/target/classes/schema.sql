CREATE TABLE IF NOT EXISTS workflow_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_type VARCHAR(100) NOT NULL,
    process_instance_key BIGINT NOT NULL,
    job_key BIGINT NOT NULL,
    correlation_key VARCHAR(255),
    variables_json CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_workflow_record_process_instance
    ON workflow_record (process_instance_key);

CREATE INDEX IF NOT EXISTS idx_workflow_record_type
    ON workflow_record (record_type);
